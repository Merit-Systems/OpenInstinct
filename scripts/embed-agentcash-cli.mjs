import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { format } from "oxfmt";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packageRoot = resolve(projectRoot, "node_modules", "agentcash");
const outputPath = resolve(
  projectRoot,
  "agent",
  "lib",
  "agentcash-cli-source.generated.ts"
);
const metadata = JSON.parse(
  await readFile(resolve(packageRoot, "package.json"), "utf8")
);
if (metadata.name !== "agentcash" || typeof metadata.version !== "string") {
  throw new Error("The installed Agentcash package has an unexpected shape.");
}
const result = await build({
  bundle: true,
  entryPoints: [resolve(packageRoot, "dist", "esm", "index.js")],
  format: "esm",
  legalComments: "none",
  platform: "node",
  target: "node22",
  write: false,
});
const source = result.outputFiles[0]?.text;
if (!source || !source.startsWith("#!/usr/bin/env node")) {
  throw new Error("The Agentcash CLI bundle could not be generated.");
}
const sha256 = createHash("sha256").update(source).digest("hex");
const generated = `// Generated by scripts/embed-agentcash-cli.mjs. Do not edit.\nexport const agentcashCliSource = ${JSON.stringify(source)};\nexport const agentcashCliVersion = ${JSON.stringify(metadata.version)};\nexport const agentcashCliSha256 = ${JSON.stringify(sha256)};\n`;
const formatted = await format(outputPath, generated, {
  printWidth: 80,
  semi: true,
  singleQuote: false,
  tabWidth: 2,
  trailingComma: "es5",
});
if (formatted.errors.length > 0) {
  throw new Error("The generated Agentcash CLI source could not be formatted.");
}
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, formatted.code, "utf8");
