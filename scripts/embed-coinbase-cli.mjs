import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "oxfmt";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packageRoot = resolve(
  projectRoot,
  "node_modules",
  "@coinbase",
  "coinbase-cli"
);
const outputPath = resolve(
  projectRoot,
  "agent",
  "lib",
  "coinbase-cli-source.generated.ts"
);
const [metadataText, source] = await Promise.all([
  readFile(resolve(packageRoot, "package.json"), "utf8"),
  readFile(resolve(packageRoot, "dist", "index.js"), "utf8"),
]);
const metadata = JSON.parse(metadataText);
if (
  metadata.name !== "@coinbase/coinbase-cli" ||
  typeof metadata.version !== "string" ||
  !source.startsWith("#!/usr/bin/env node") ||
  !source.includes("coinbase mcp")
) {
  throw new Error(
    "The installed Coinbase CLI package has an unexpected shape."
  );
}
const sha256 = createHash("sha256").update(source).digest("hex");
const generated = `// Generated by scripts/embed-coinbase-cli.mjs. Do not edit.\nexport const coinbaseCliSource = ${JSON.stringify(source)};\nexport const coinbaseCliVersion = ${JSON.stringify(metadata.version)};\nexport const coinbaseCliSha256 = ${JSON.stringify(sha256)};\n`;
const formatted = await format(outputPath, generated, {
  printWidth: 80,
  semi: true,
  singleQuote: false,
  tabWidth: 2,
  trailingComma: "es5",
});
if (formatted.errors.length > 0) {
  throw new Error("The generated Coinbase CLI source could not be formatted.");
}
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, formatted.code, "utf8");
